'use strict';
const assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const { MeshGeometry } = require('../geometry');
const P = require('../../../shared/protocol');
const bus = new EventEmitter(), peerEvents = new EventEmitter(), screen = new EventEmitter();
const sent = [];
bus.onPeer = (event, fn) => peerEvents.on(event, fn);
bus.connectedIds = () => ['B','C'];
bus.send = (id, msg) => sent.push({id,msg});
screen.getAllDisplays = () => [{id: 1, bounds: {x:0,y:0,width:1920,height:1080}, scaleFactor:1}];
let changes = 0;
const map = new MeshGeometry({bus, screen, edges: () => ({right:'B',top:'C'}), changed: () => changes++});
bus.emit(P.T.KVM_DISPLAYS, {displays:[{id:'b',x:0,y:0,w:1920,h:540,scale:1}]}, 'B');
assert.equal(map.zones(['right']).right, '0.2500-0.7500');
assert.equal(map.toPeer('B','right',0.25),0);
assert.equal(map.toPeer('B','right',0.75),1);
peerEvents.emit('welcome','C');
assert.equal(sent.at(-1).id,'C');
assert.equal(sent.at(-1).msg.t,P.T.KVM_DISPLAYS);
screen.emit('display-metrics-changed');
assert.equal(sent.length,3);
assert(changes >= 3);
peerEvents.emit('closed','B');
assert.equal(map.peers.has('B'),false);
map.destroy();
assert.equal(screen.listenerCount('display-added'),0);
console.log('passed: mesh geometry zones, landing conversion, monitor refresh and cleanup');
