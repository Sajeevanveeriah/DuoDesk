func check(_ condition: Bool, _ name: String) {
  if !condition { fatalError("FAIL: " + name) }
}
let main = EdgeRect(x: 0, y: 0, width: 1920, height: 1080)
let right = EdgeRect(x: 1920, y: 100, width: 1280, height: 1024)
check(EdgePolicy.isOuter(1919, 50, side: "right", displays: [main,right]), "exposed segment")
check(!EdgePolicy.isOuter(1919, 500, side: "right", displays: [main,right]), "internal seam")
check(EdgePolicy.isOuter(3199, 500, side: "right", displays: [main,right]), "outer right")
let gap = EdgeRect(x: 2000, y: 0, width: 1000, height: 1000)
check(!EdgePolicy.isOuter(1919, 500, side: "right", displays: [main,gap]), "monitor beyond gap")
let left = EdgeRect(x: -1280, y: -200, width: 1280, height: 1024)
check(!EdgePolicy.isOuter(0, 100, side: "left", displays: [main,left]), "negative coordinates seam")
check(EdgePolicy.isOuter(-1280, 100, side: "left", displays: [main,left]), "negative outer left")
let above = EdgeRect(x: 0, y: -1080, width: 1920, height: 1080)
check(!EdgePolicy.isOuter(500, 0, side: "top", displays: [main,above]), "top seam")
check(EdgePolicy.isOuter(500, -1080, side: "top", displays: [main,above]), "top outer")
check(!EdgePolicy.isOuter(500, 500, side: "right", displays: [main]), "not at edge")
check(!EdgePolicy.isOuter(500, 500, side: "bad", displays: [main]), "invalid side")
check(EdgePolicy.guardReason(buttonsHeld: true, elapsed: 10, cooldown: 0.25) == "button", "held button")
check(EdgePolicy.guardReason(buttonsHeld: false, elapsed: 0.249, cooldown: 0.25) == "cooldown", "cooldown")
check(EdgePolicy.guardReason(buttonsHeld: false, elapsed: 0.25, cooldown: 0.25) == nil, "cooldown ends")
var limiter = EdgeLogLimiter()
check(limiter.allow(0), "first refusal logged")
check(!limiter.allow(1.999), "global throttling")
check(limiter.allow(2), "two second interval")
check(EdgePolicy.arrivalBlocked(elapsed: 0.1, inward: 0, window: 0.5), "arrival guard")
check(!EdgePolicy.arrivalBlocked(elapsed: 0.5, inward: 0, window: 0.5), "arrival expires")
check(!EdgePolicy.arrivalBlocked(elapsed: 0.1, inward: 8, window: 0.5), "inward movement rearms")
check(EdgePolicy.inZone(0.5, [0.2...0.7]), "inside zone")
check(!EdgePolicy.inZone(0.9, [0.2...0.7]), "outside zone")
check(!EdgePolicy.inZone(0.5, []), "no shared edge")
check(EdgePolicy.inZone(0.5, nil), "legacy peer full edge")
